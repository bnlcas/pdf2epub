#!/bin/bash
# Writes the Finder Quick Action "Convert to EPUB.workflow" into the given directory.
#
#   Scripts/make-quick-action.sh <output-dir>
#
# The action runs pdf2epub on each selected PDF (looking in ~/bin, /usr/local/bin and
# /opt/homebrew/bin) with a progress window, and posts a notification when each finishes.
set -euo pipefail

out="${1:?usage: make-quick-action.sh <output-dir>}"
wf="$out/Convert to EPUB.workflow"
rm -rf "$wf"
mkdir -p "$wf/Contents"

# The shell script the action runs. Kept free of characters that need XML escaping
# other than & < > (escaped below).
read -r -d '' SCRIPT <<'SH' || true
for dir in "$HOME/bin" /usr/local/bin /opt/homebrew/bin; do
  [ -x "$dir/pdf2epub" ] && PDF2EPUB="$dir/pdf2epub" && break
done
notify() {
  /usr/bin/osascript - "$1" "$2" <<'OSA'
on run argv
  display notification (item 2 of argv) with title (item 1 of argv)
end run
OSA
}
if [ -z "${PDF2EPUB:-}" ]; then
  notify "PDF to EPUB" "pdf2epub is not installed. Run the installer again."
  exit 1
fi
for f in "$@"; do
  name="$(basename "$f")"
  log="$("$PDF2EPUB" --progress-window "$f" 2>&1)"
  status=$?
  if [ $status -eq 0 ]; then
    notify "PDF to EPUB" "Done: ${name%.*}.epub"
  elif [ $status -eq 2 ]; then
    notify "PDF to EPUB" "Done with warnings: ${name%.*}.epub"
  else
    notify "PDF to EPUB" "Could not convert $name: $(printf '%s' "$log" | tail -n 1)"
  fi
done
SH

xml_escape() { sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g'; }
ESCAPED="$(printf '%s' "$SCRIPT" | xml_escape)"

